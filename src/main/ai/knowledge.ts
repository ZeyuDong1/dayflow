/** 首次启动时把知识库种进 ai-memory(幂等,已存在不覆盖)。 */
export async function seedKnowledge(): Promise<void> {
  for (const page of KNOWLEDGE_PAGES) {
    try {
      if ((await memoryReadPage(page.path)) === null) {
        await memoryWritePage(page.path, page.body, page.title)
      }
    } catch {
      // 记忆服务不可用时跳过,prompt 内的底座仍够用
    }
  }
}
